// The two patterns yamlScalar needs. A value that is all "plain" characters
// can be emitted bare; anything else is quoted with JSON rules, which is valid
// YAML double-quoted style.
var (
	yamlPlainRE = regexp.MustCompile(`^[A-Za-z0-9_./:@*+-]+$`)
	// These read as booleans or null in YAML 1.1, so they must be quoted or
	// cloudflared would see true instead of the string "true".
	yamlKeywordRE = regexp.MustCompile(`^(?i:true|false|null|yes|no|on|off|~)$`)
)

// yamlScalar renders one YAML scalar, byte for byte as the previous
// implementation did.
func yamlScalar(value string) string {
	if value == "" {
		return `""`
	}
	if yamlPlainRE.MatchString(value) && !yamlKeywordRE.MatchString(value) {
		return value
	}
	// JSON string escaping is valid YAML double-quoted style. SetEscapeHTML is
	// off so "<" and "&" stay literal, as JSON.stringify left them.
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(value); err != nil {
		return `""`
	}
	return strings.TrimRight(buf.String(), "\n")
}

// BuildConfigYAML renders the config.yml of a locally-managed tunnel.
//
// The catch-all rule is not optional: cloudflared refuses a config whose
// ingress has no final catch-all, and without it a typo in the hostname answers
// a raw cloudflared error page instead of the intended status.
func BuildConfigYAML(t config.Tunnel, credentialsFile string) string {
	lines := make([]string, 0, 16)
	lines = append(lines, "# Generated by Cloudflare Tunnel for fnOS. Manual edits are overwritten.")

	tunnelRef := t.TunnelID
	if tunnelRef == "" {
		tunnelRef = t.TunnelName
	}
	if tunnelRef != "" {
		lines = append(lines, "tunnel: "+yamlScalar(tunnelRef))
	}
	if credentialsFile != "" {
		lines = append(lines, "credentials-file: "+yamlScalar(credentialsFile))
	}

	lines = append(lines, "ingress:")
	for _, rule := range t.Ingress {
		if rule.Hostname == "" {
			continue
		}
		lines = append(lines, "  - hostname: "+yamlScalar(rule.Hostname))
		if rule.Path != "" {
			lines = append(lines, "    path: "+yamlScalar(rule.Path))
		}
		service := rule.Service
		if service == "" {
			service = "http://127.0.0.1:80"
		}
		lines = append(lines, "    service: "+yamlScalar(service))

		type entry struct{ key, value string }
		origin := make([]entry, 0, 3)
		if rule.NoTLSVerify {
			origin = append(origin, entry{"noTLSVerify", "true"})
		}
		if rule.OriginServerName != "" {
			origin = append(origin, entry{"originServerName", rule.OriginServerName})
		}
		if rule.HTTPHostHeader != "" {
			origin = append(origin, entry{"httpHostHeader", rule.HTTPHostHeader})
		}
		if len(origin) > 0 {
			lines = append(lines, "    originRequest:")
			for _, e := range origin {
				lines = append(lines, "      "+e.key+": "+yamlScalar(e.value))
			}
		}
	}

	catchAll := t.CatchAll
	if catchAll == "" {
		catchAll = "http_status:404"
	}
	lines = append(lines, "  - service: "+yamlScalar(catchAll))

	return strings.Join(lines, "\n") + "\n"
}

// ResolveCredentials returns the credentials file of a locally-managed tunnel,
// or "" when no answer is provable.
//
// Only two answers count: an explicit path, or the file named after the tunnel
// UUID that `cloudflared tunnel create` wrote. Falling back to "some .json in
// the directory" would silently run a different tunnel -- which looks exactly
// like a healthy tunnel serving the wrong origin. Callers resolve a name to a
// UUID first (ResolveTunnelIDByName) and then store it.
func (r *Runner) ResolveCredentials(t config.Tunnel) string {
	if t.CredentialsFile != "" {
		if fsx.Exists(t.CredentialsFile) {
			return t.CredentialsFile
		}
		return ""
	}
	if t.TunnelID != "" && config.UUIDRE.MatchString(strings.ToLower(t.TunnelID)) {
		candidate := r.p.CredentialFile(t.TunnelID)
		if fsx.Exists(candidate) {
			return candidate
		}
	}
	return ""
}

// WriteTunnelConfig writes the generated config.yml for a locally-managed
// tunnel. It is the single writer of that file, shared by BuildArgs and by the
// supervisor's ApplyLocalConfig.
func (r *Runner) WriteTunnelConfig(t config.Tunnel, cred string) (string, error) {
	configPath := r.p.TunnelConfig(t.ID)
	// fsx.WritePrivate creates the parent directory and writes atomically, so a
	// half-written config.yml can never be picked up by a starting tunnel.
	if err := fsx.WritePrivate(configPath, []byte(BuildConfigYAML(t, cred))); err != nil {
		return "", err
	}
	return configPath, nil
}

// BuildArgs returns the argv and the extra environment for one tunnel.
//
// The token travels through the environment, never through argv: a process
// command line is world-readable via /proc, so `--token` would expose the
// credential to every local user. cloudflared honours TUNNEL_TOKEN.
func (r *Runner) BuildArgs(t config.Tunnel, s config.Settings) (args []string, env map[string]string, err error) {
	args = GlobalArgs(s)
	env = map[string]string{}

	switch t.Type {
	case config.TypeToken:
		if t.Token == "" {
			return nil, nil, fmt.Errorf("未配置隧道 Token")
		}
		args = append(args, "tunnel", "run")
		env["TUNNEL_TOKEN"] = t.Token

	case config.TypeQuick:
		if t.Target == "" {
			return nil, nil, fmt.Errorf("未配置本地服务地址")
		}
		args = append(args, "tunnel", "--url", t.Target)
		if t.QuickHostname != "" {
			args = append(args, "--hostname", t.QuickHostname)
		}

	case config.TypeLocal:
		if t.TunnelName == "" && t.TunnelID == "" {
			return nil, nil, fmt.Errorf("未选择已创建的隧道")
		}
		cred := r.ResolveCredentials(t)
		if cred == "" {
			if t.TunnelID != "" {
				return nil, nil, fmt.Errorf(
					"找不到隧道凭据文件 %s，请先在“账户”页重新创建或重新选择该隧道",
					r.p.CredentialFile(t.TunnelID))
			}
			return nil, nil, fmt.Errorf(
				"无法确定隧道「%s」的 UUID，请在“账户”页重新选择该隧道（需要已登录账户）",
				t.TunnelName)
		}
		configPath, werr := r.WriteTunnelConfig(t, cred)
		if werr != nil {
			return nil, nil, fmt.Errorf("写入配置文件失败: %s", werr.Error())
		}
		args = append(args, "--config", configPath)
		ref := t.TunnelName
		if ref == "" {
			ref = t.TunnelID
		}
		args = append(args, "tunnel", "run", ref)

	case config.TypeConfig:
		if t.ConfigFile == "" {
			return nil, nil, fmt.Errorf("未指定配置文件路径")
		}
		if !fsx.Exists(t.ConfigFile) {
			return nil, nil, fmt.Errorf("配置文件不存在: %s", t.ConfigFile)
		}
		args = append(args, "--config", t.ConfigFile)
		args = append(args, "tunnel", "run")

	default:
		return nil, nil, fmt.Errorf("未知的隧道类型: %s", t.Type)
	}

	if t.ExtraArgs != "" {
		args = append(args, SplitArgs(t.ExtraArgs)...)
	}
	return args, env, nil
}

// ResolveTunnelIDByName maps a tunnel name to its UUID through the account
// tunnel list. Best effort: without a login (or without network) the name stays
// unresolved and the caller reports it.
func (r *Runner) ResolveTunnelIDByName(name string) string {
	if name == "" {
		return ""
	}
	listed, err := r.ListTunnels()
	if err != nil {
		return ""
	}
	for _, t := range listed {
		if t.Name == name {
			return t.ID
		}
	}
	return ""
}
